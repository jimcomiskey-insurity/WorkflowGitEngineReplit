using Reqnroll;
using FluentAssertions;
using WorkflowConfig.E2E.Tests.Support;
using WorkflowConfig.E2E.Tests.Generated;
using WorkflowConfig.E2E.Tests.Generated.Contracts;

namespace WorkflowConfig.E2E.Tests.StepDefinitions;

[Binding]
public class DataStoreGitIntegrationSteps
{
    private const string ProgramId = "default";
    private readonly ScenarioContext _scenarioContext;
    private readonly HttpClient _httpClient;
    private readonly IApiClient _apiClient;
    private string _userId = string.Empty;
    private string _branchName = string.Empty;
    private string _datastoreId = string.Empty;
    private int _pullRequestId = 0;

    public DataStoreGitIntegrationSteps(ScenarioContext scenarioContext)
    {
        _scenarioContext = scenarioContext;
        _httpClient = new HttpClient
        {
            BaseAddress = new Uri(TestConfiguration.BackendUrl)
        };
        _apiClient = new ApiClient(TestConfiguration.BackendUrl, _httpClient);
    }

    [Given(@"the repository is reset to initial state for user ""(.*)""")]
    public async Task GivenTheRepositoryIsResetToInitialStateForUser(string userId)
    {
        _userId = userId;
        
        // Call reset endpoint using generated client
        await _apiClient.ResetRepositoriesAsync(userId, ProgramId);
        
        await Task.Delay(1000); // Give time for reset to complete
    }

    [When(@"I create a new branch ""(.*)"" for user ""(.*)""")]
    public async Task WhenICreateANewBranchForUser(string branchName, string userId)
    {
        _branchName = branchName;
        
        // Create the branch using generated client
        await _apiClient.CreateBranchAsync(userId, ProgramId, new BranchRequest { BranchName = branchName });
        
        await Task.Delay(300);
        
        // Switch to the new branch (API doesn't auto-switch like the frontend)
        await _apiClient.SwitchBranchAsync(userId, ProgramId, new BranchRequest { BranchName = branchName });
        
        await Task.Delay(500); // Give time for branch switch
    }

    [When(@"I create a new datastore with the following details for user ""(.*)"":")]
    public async Task WhenICreateANewDatastoreWithTheFollowingDetailsForUser(string userId, Table table)
    {
        var name = table.Rows.First(r => r["Field"] == "Name")["Value"];
        var description = table.Rows.First(r => r["Field"] == "Description")["Value"];
        
        // Create datastore using generated client
        var datastore = await _apiClient.CreateDataStoreAsync(userId, ProgramId, new DataStore 
        { 
            Id = string.Empty, // ID is generated by backend
            Name = name,
            Description = description,
            DataGroups = new List<DataGroup>()
        });
        
        datastore.Should().NotBeNull("Datastore should be created");
        _datastoreId = datastore.Id;
        _datastoreId.Should().NotBeNullOrEmpty("Datastore ID should be returned");
        
        _scenarioContext["DatastoreId"] = _datastoreId;
        _scenarioContext["DatastoreName"] = name;
    }

    [Then(@"the datastore should appear in the datastore list for user ""(.*)""")]
    public async Task ThenTheDatastoreShouldAppearInTheDatastoreListForUser(string userId)
    {
        // Get all datastores using generated client
        var datastores = await _apiClient.GetAllDataStoresAsync(userId, ProgramId);
        datastores.Should().NotBeNull();
        
        var foundDatastore = datastores.FirstOrDefault(ds => ds.Id == _datastoreId);
        
        foundDatastore.Should().NotBeNull($"Datastore with ID {_datastoreId} should exist in the list");
    }

    [When(@"I commit the changes with message ""(.*)"" for user ""(.*)""")]
    public async Task WhenICommitTheChangesWithMessageForUser(string message, string userId)
    {
        // Commit using generated client
        await _apiClient.CommitAsync(userId, ProgramId, new CommitRequest 
        { 
            Message = message,
            AuthorName = "Test User",
            AuthorEmail = "test@example.com"
        });
        
        await Task.Delay(500); // Give time for commit
    }

    [When(@"I push the changes for user ""(.*)""")]
    public async Task WhenIPushTheChangesForUser(string userId)
    {
        // Push using generated client - must succeed for PR creation
        await _apiClient.PushAsync(userId, ProgramId);
        
        await Task.Delay(1000); // Give time for push
    }

    [When(@"I create a pull request from ""(.*)"" to ""(.*)"" for user ""(.*)""")]
    public async Task WhenICreateAPullRequestFromToForUser(string sourceBranch, string targetBranch, string userId)
    {
        // Create PR using generated client
        var pullRequest = await _apiClient.CreatePullRequestAsync(userId, ProgramId, new CreatePullRequestRequest
        {
            Title = "Test PR",
            Description = "Test pull request for datastore changes",
            SourceBranch = sourceBranch,
            TargetBranch = targetBranch
        });
        
        pullRequest.Should().NotBeNull("Pull request should be created");
        _pullRequestId = pullRequest.Number;
        _pullRequestId.Should().BeGreaterThan(0, "Pull request number should be returned");
        
        // Store commit SHAs for later verification
        _scenarioContext["PullRequestId"] = _pullRequestId;
        _scenarioContext["SourceCommitSha"] = pullRequest.SourceCommitSha;
        _scenarioContext["TargetCommitSha"] = pullRequest.TargetCommitSha;
        
        await Task.Delay(500); // Give time for PR creation
    }

    [Then(@"the pull request comparison should contain the datastore in dataStoreChanges")]
    public async Task ThenThePullRequestComparisonShouldContainTheDatastoreInDataStoreChanges()
    {
        // Get PR comparison using generated client (uses PR number)
        var comparison = await _apiClient.GetBranchComparisonAsync(_userId, ProgramId, _pullRequestId);
        comparison.Should().NotBeNull("Comparison should be returned");
        
        Console.WriteLine($"Comparison has {comparison.DataStoreChanges?.Count ?? 0} datastore changes");
        
        // Check if dataStoreChanges exists and contains our datastore
        comparison.DataStoreChanges.Should().NotBeNull("Comparison should have dataStoreChanges property");
        comparison.DataStoreChanges.Should().NotBeEmpty("dataStoreChanges should contain at least one change");
        
        var datastoreName = _scenarioContext["DatastoreName"].ToString();
        var foundDatastore = comparison.DataStoreChanges.FirstOrDefault(
            ds => ds.DataStoreName == datastoreName);
        
        foundDatastore.Should().NotBeNull($"Datastore '{datastoreName}' should appear in comparison.dataStoreChanges");
        foundDatastore!.ChangeType.Should().Be("added", "Datastore should be marked as added");
        
        // Store comparison for next step
        _scenarioContext["Comparison"] = comparison;
    }

    [Then(@"at least one commit in the pull request should contain the datastore in dataStoreChanges")]
    public async Task ThenAtLeastOneCommitInThePullRequestShouldContainTheDatastoreInDataStoreChanges()
    {
        var comparison = (BranchComparison)_scenarioContext["Comparison"];
        
        // Check if commits exist
        comparison.Commits.Should().NotBeNull("Comparison should have commits property");
        comparison.Commits.Should().NotBeEmpty("Pull request should have at least one commit");
        
        var datastoreName = _scenarioContext["DatastoreName"].ToString();
        
        // Find a commit that has our datastore in its changes
        var commitWithDatastore = comparison.Commits.FirstOrDefault(commit =>
            commit.DataStoreChanges != null &&
            commit.DataStoreChanges.Any(ds => ds.DataStoreName == datastoreName));
        
        commitWithDatastore.Should().NotBeNull(
            $"At least one commit should contain datastore '{datastoreName}' in its dataStoreChanges property.");
        
        var changeInCommit = commitWithDatastore!.DataStoreChanges!.First(ds => ds.DataStoreName == datastoreName);
        changeInCommit.ChangeType.Should().Be("added", "Datastore should be marked as added in commit");
    }
}
